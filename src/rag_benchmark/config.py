"""
Configuration schema for the Enterprise RAG benchmark pipeline.
"""
from pydantic import BaseModel, Field


class RAGConfig(BaseModel):
    # Dataset
    dataset_name: str = Field(
        default="ingalepratap/EnterpriseRAG-Bench",
        description="Hugging Face benchmark dataset name",
    )

    # Storage
    storage_path: str = Field(
        default="data/qdrant_db",
        description="Path to local on-disk Qdrant RocksDB storage",
    )
    collection_name: str = Field(
        default="enterprise_rag_chunks",
        description="Name of the Qdrant vector collection",
    )

    # Models
    embedding_model: str = Field(
        default="sentence-transformers/all-MiniLM-L6-v2",
        description="Sentence-transformer dense embedding model",
    )
    vector_dim: int = Field(
        default=384,
        description="Dimensionality of dense vectors (384 for all-MiniLM-L6-v2)",
    )
    reranker_model: str = Field(
        default="cross-encoder/ms-marco-MiniLM-L-6-v2",
        description="Cross-encoder reranker model",
    )
    generator_model: str = Field(
        default="Qwen/Qwen2.5-0.5B-Instruct",
        description="Local Hugging Face generative model for grounded answering",
    )

    # Chunking
    parent_chunk_size: int = Field(
        default=3000,
        description="Parent chunk size in characters for LLM hydration",
    )
    parent_chunk_overlap: int = Field(
        default=300,
        description="Overlap between adjacent parent chunks",
    )
    child_chunk_size: int = Field(
        default=800,
        description="Child chunk size in characters for dense/sparse retrieval",
    )
    child_chunk_overlap: int = Field(
        default=100,
        description="Overlap between adjacent child chunks",
    )

    # Retrieval & Ranking
    hybrid_top_k: int = Field(
        default=50,
        description="Number of candidate chunks returned by Hybrid (Dense + BM25) search",
    )
    rerank_top_n: int = Field(
        default=3,
        description="Number of top candidates passed to Generator after Cross-Encoder reranking",
    )
    rrf_k: int = Field(
        default=60,
        description="Reciprocal Rank Fusion smoothing constant k",
    )

    # Generation
    max_new_tokens: int = Field(
        default=450,
        description="Maximum new tokens generated by the LLM",
    )
    use_lost_in_middle: bool = Field(
        default=False,
        description="Whether to order documents using Lost-in-the-Middle heuristic",
    )